import assert from 'node:assert/strict';
import { LiveSnapshot, liveRoute } from '../cloudflare-relay/live.js';
const mem = new Map();
const storage = {get: async k=>mem.get(k), put:async(k,v)=>mem.set(k,v), delete:async k=>mem.delete(k), transaction:async fn=>fn(storage)};
const object = new LiveSnapshot({storage}, {});
const env = {LIVE_KEY:'test-only', LIVE:{idFromName:x=>x,get:()=>object}};
const bytes = new TextEncoder().encode('AQ5w1'+'x'.repeat(80));
const digest = Buffer.from(await crypto.subtle.digest('SHA-256', bytes)).toString('hex');
const frame = {stream_id:'test', sequence:1, role:'diagnostic', sent_at:Date.now(), public:{time:'fixture',phase:'closed',version:'test',pick_quotes:{},indices:[],quote_time:null},private_b64:Buffer.from(bytes).toString('base64'),private_pack_sha256:digest};
const request=(method='GET', body, key='test-only', suffix='')=> new Request('https://relay.test/__aq5/live'+suffix+(suffix.includes('?')?'&':'?')+'channel=diagnostic',{method,headers:{'x-aq5-live-key':key},...(body?{body:JSON.stringify(body)}:{})});
assert.equal((await liveRoute(request('POST',frame,'wrong'),env)).status,403);
assert.equal((await liveRoute(request('POST',{...frame,public:{...frame.public,plan:{}}}),env)).status,400);
assert.equal((await liveRoute(request('POST',{...frame,private_b64:'plain-private'}),env)).status,400);
assert.equal((await liveRoute(request('POST',frame),env)).status,200);
assert.equal((await liveRoute(request('POST',frame),env)).status,409);
const meta=await(await liveRoute(request(),env)).json(); assert.equal(meta.available,true); assert.ok(!('private_b64' in meta));
assert.equal((await liveRoute(request('GET',null,'','/private.enc?v=wrong'),env)).status,409);
assert.equal((await liveRoute(request('GET',null,'','/private.enc?v='+digest),env)).status,200);
mem.get('snapshot').received_at-=46000;
assert.equal((await(await liveRoute(request(),env)).json()).available,false);
assert.equal((await liveRoute(request('DELETE'),env)).status,200);
assert.equal((await(await liveRoute(request(),env)).json()).available,false);
